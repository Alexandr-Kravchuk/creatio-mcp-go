#!/usr/bin/env python3
"""Write the fake-stand answers the push-workspace / restore-workspace scenarios (sync.json) serve.

  sync-UsrPkg.zip            PackageInstallerService GetZipPackages for ["UsrPkg"]: a zip holding UsrPkg.gz
  sync-UsrSecond.zip         the same for ["UsrSecond"]
  sync-UsrPkg-autogen.gz     CreatioApiGateway GetAutogeneratedFolder for "UsrPkg"
  sync-UsrSecond-autogen.gz  the same for "UsrSecond"

A .gz is clio's package stream (CompressionUtilities): per file the relative path as an Int32 count of UTF-16
units and the units, then the content as an Int32 length and the bytes, little-endian, gzipped. Paths use
backslashes, as an archive packed on Windows does. Fixed timestamps keep the files reproducible.

    python3 scripts/workspace-scenarios/make-sync-fixtures.py
"""
import gzip, io, pathlib, struct, zipfile

FIXTURES = pathlib.Path(__file__).resolve().parent / "fixtures"


def clio_gz(files):
    raw = io.BytesIO()
    for name, content in files:
        units = name.encode("utf-16-le")
        raw.write(struct.pack("<i", len(units) // 2))
        raw.write(units)
        data = content.encode("utf-8") if isinstance(content, str) else content
        raw.write(struct.pack("<i", len(data)))
        raw.write(data)
    return gzip.compress(raw.getvalue(), mtime=0)


def package_zip(name, files):
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        info = zipfile.ZipInfo(f"{name}.gz", date_time=(2026, 1, 1, 0, 0, 0))
        info.compress_type = zipfile.ZIP_DEFLATED
        archive.writestr(info, clio_gz(files))
    return buffer.getvalue()


