#!/usr/bin/env python3
"""Regenerate internal/pagesmoke/scripts_gen.go from clio's FreedomUiPageScripts.cs.

page-smoke's page scripts are C# raw string literals in clio
(clio/Command/RuntimeVerification/FreedomUiPageScripts.cs). This script reads the five literals - the shared
prelude and the bodies of the ready, inventory, overlay and click scripts - applies C#'s raw-string rules (the
content lines between the opening and the closing quotes, each with the closing quotes' indentation removed) and
writes them as Go constants. internal/pagesmoke/scripts.go joins them exactly as the C# expressions do.

    python3 scripts/generate-page-smoke-scripts.py --clio-source <clio checkout>
"""
import argparse, pathlib, re, subprocess, sys

REPO = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = REPO / "internal/pagesmoke/scripts_gen.go"
SOURCE = "clio/Command/RuntimeVerification/FreedomUiPageScripts.cs"

# The literal that follows each anchor, in the order the file declares them.
LITERALS = [
    ("pagePrelude", "private const string Prelude = "),
    ("readyBody", "internal const string ReadyScript = "),
    ("inventoryBody", "internal static readonly string InventoryScript = "),
    ("overlayBody", "internal static readonly string OverlayScript = "),
    ("clickBody", "internal static string BuildClickScript(string button) =>"),
]


def raw_literal(text, start):
    """The value of the first multi-line raw string literal (three quotes) after start, and where it ends."""
    opening = text.index('"""', start)
    line_end = text.index("\n", opening)
    if text[opening + 3:line_end].strip():
        raise SystemExit("a raw string literal does not start on its own line")
    closing = text.index('"""', line_end)
    closing_line = text.rindex("\n", 0, closing) + 1
    indentation = text[closing_line:closing]
    if indentation.strip():
        raise SystemExit("the closing quotes do not start their line")
    lines = text[line_end + 1:closing_line - 1].split("\n")
    content = []
    for line in lines:
        if line.strip() == "":
            content.append("")
            continue
        if not line.startswith(indentation):
            raise SystemExit("a content line is indented less than the closing quotes")
        content.append(line[len(indentation):])
    return "\n".join(content), closing + 3


def go_string(value):
    if "`" not in value:
        return "`" + value + "`"
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t") + '"'


def generate(source_text):
    out = ["// Code generated by `python3 scripts/generate-page-smoke-scripts.py` from clio 8.1.0.142's",
           "// " + SOURCE + ". DO NOT EDIT.", "", "package pagesmoke", "", "const ("]
    position = 0
    for name, anchor in LITERALS:
        start = source_text.index(anchor, position)
        value, position = raw_literal(source_text, start)
        out.append("\t" + name + " = " + go_string(value))
    out.append(")")
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--clio-source", required=True, help="clio checkout (8.1.0.142)")
    parser.add_argument("--check", action="store_true", help="fail when the committed file differs instead of writing it")
    options = parser.parse_args()
    source = (pathlib.Path(options.clio_source) / SOURCE).read_text(encoding="utf-8-sig").replace("\r\n", "\n")
    generated = generate(source)
    if options.check:
        if OUTPUT.read_text(encoding="utf-8") != generated:
            sys.exit(f"{OUTPUT.relative_to(REPO)} is not what the generator writes from {SOURCE}")
        return
    OUTPUT.write_text(generated, encoding="utf-8")
    subprocess.run(["gofmt", "-w", str(OUTPUT)], check=True)


if __name__ == "__main__":
    main()
