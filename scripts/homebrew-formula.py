#!/usr/bin/env python3
"""Writes the Homebrew formula (and the tap README) for a published creatio-mcp-go release.

The formula installs the prebuilt release archives; it does not build from source. Each macOS and
Linux archive gets its own URL and sha256, both taken from the release's SHA256SUMS. There is no
`version` line: Homebrew scans it from the archive name (also a suffix like 0.3.0-rc.1), and
`brew audit --strict` rejects a version that repeats the scanned one.

Usage:
  scripts/homebrew-formula.py --version v0.2.0 --sums dist/SHA256SUMS --out <tap-dir>
  scripts/homebrew-formula.py --version v0.2.0 --out <tap-dir>     (reads SHA256SUMS of the release)

Writes <tap-dir>/Formula/creatio-mcp-go.rb and, with --readme, <tap-dir>/README.md.
"""
import argparse
import pathlib
import re
import sys
import urllib.request

NAME = "creatio-mcp-go"
DEFAULT_REPO = "Alexandr-Kravchuk/creatio-mcp-go"
DEFAULT_TAP = "Alexandr-Kravchuk/homebrew-tap"
# (Homebrew OS block, Homebrew CPU block, archive os, archive arch)
PLATFORMS = [
    ("on_macos", "on_arm", "darwin", "arm64"),
    ("on_macos", "on_intel", "darwin", "amd64"),
    ("on_linux", "on_arm", "linux", "arm64"),
    ("on_linux", "on_intel", "linux", "amd64"),
]
VERSION_RE = re.compile(r"^v?([0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?)$")
SHA_RE = re.compile(r"^[0-9a-f]{64}$")


class FormulaError(Exception):
    pass


def normalize_version(value):
    """Returns the version without the leading v; rejects anything that is not vX.Y.Z[-suffix]."""
    match = VERSION_RE.match(value.strip())
    if not match:
        raise FormulaError(f"not a release version: {value!r} (expected vX.Y.Z or vX.Y.Z-suffix)")
    return match.group(1)


def parse_sums(text):
    """Parses `shasum -a 256` output into {file name: sha256}."""
    sums = {}
    for number, line in enumerate(text.splitlines(), 1):
        if not line.strip():
            continue
        parts = line.split()
        if len(parts) != 2:
            raise FormulaError(f"SHA256SUMS line {number} is not '<sha256>  <file>': {line!r}")
        digest, name = parts[0].lower(), parts[1].lstrip("*")
        if not SHA_RE.match(digest):
            raise FormulaError(f"SHA256SUMS line {number} has no valid sha256: {line!r}")
        sums[name] = digest
    return sums


def archive_name(version, goos, goarch):
    return f"{NAME}_{version}_{goos}_{goarch}.tar.gz"


def release_url(repo, version, file_name):
    return f"https://github.com/{repo}/releases/download/v{version}/{file_name}"


def platform_assets(version, sums, repo=DEFAULT_REPO):
    """Returns [(os block, cpu block, url, sha256)] or fails naming every archive SHA256SUMS lacks."""
    assets, missing = [], []
    for os_block, cpu_block, goos, goarch in PLATFORMS:
        name = archive_name(version, goos, goarch)
        if name not in sums:
            missing.append(name)
            continue
        assets.append((os_block, cpu_block, release_url(repo, version, name), sums[name]))
    if missing:
        raise FormulaError("SHA256SUMS has no entry for: " + ", ".join(missing))
    return assets


def render_formula(version, sums, repo=DEFAULT_REPO):
    assets = platform_assets(version, sums, repo)
    blocks = []
    for os_block in ("on_macos", "on_linux"):
        inner = []
        for asset_os, cpu_block, url, digest in assets:
            if asset_os != os_block:
                continue
            inner.append(
                f"    {cpu_block} do\n"
                f'      url "{url}"\n'
                f'      sha256 "{digest}"\n'
                f"    end"
            )
        blocks.append(f"  {os_block} do\n" + "\n".join(inner) + "\n  end")
    platform_blocks = "\n\n".join(blocks)
    return f'''# Generated by scripts/homebrew-formula.py in {repo}; do not edit by hand.
class CreatioMcpGo < Formula
  desc "MCP server for Creatio, a drop-in replacement for clio's MCP server"
  homepage "https://github.com/{repo}"
  license "MIT"

{platform_blocks}

  def install
    bin.install "creatio-mcp-go"
  end

  def caveats
    <<~EOS
      Register the server with Claude Code (every project):
        claude mcp add --scope user creatio-go -- #{{opt_bin}}/creatio-mcp-go

      or with Codex:
        codex mcp add creatio-go -- #{{opt_bin}}/creatio-mcp-go

      The opt path stays the same across upgrades, so the registration survives `brew upgrade`.
      Environments come from clio's appsettings.json ($HOME/creatio/clio/appsettings.json, or
      $CLIO_HOME/appsettings.json); register them with `clio reg-web-app`.
    EOS
  end

  test do
    assert_equal "v#{{version}}", shell_output("#{{bin}}/creatio-mcp-go --version").strip
  end
end
'''


def render_readme(tap=DEFAULT_TAP, repo=DEFAULT_REPO):
    owner, tap_repo = tap.split("/", 1)
    short = f"{owner.lower()}/{tap_repo.removeprefix('homebrew-')}"
    return f"""# {tap_repo}

Homebrew formulae for [creatio-mcp-go](https://github.com/{repo}), an MCP server for Creatio
that works as a drop-in replacement for clio's MCP server. The formula installs the signed and
notarized release binaries for macOS (arm64, Intel) and the Linux binaries (arm64, x86_64).

```bash
brew install {short}/{NAME}
```

Then register it, for example with Claude Code:

```bash
claude mcp add --scope user creatio-go -- "$(brew --prefix)/opt/{NAME}/bin/{NAME}"
```

`brew info {NAME}` prints the Codex command too. Environments come from clio's `appsettings.json`;
see the [installation guide](https://github.com/{repo}/blob/main/docs/install.md).

`Formula/{NAME}.rb` is generated by `scripts/homebrew-formula.py` in the creatio-mcp-go repository
when a release is cut (`scripts/release.sh`); do not edit it by hand.
"""


def read_sums(source, repo, version):
    if source and not re.match(r"^https?://", source):
        return pathlib.Path(source).read_text(encoding="utf-8")
    url = source or release_url(repo, version, "SHA256SUMS")
    with urllib.request.urlopen(url, timeout=60) as response:
        return response.read().decode("utf-8")


def main(argv=None):
    parser = argparse.ArgumentParser(description="Write the Homebrew formula for a creatio-mcp-go release.")
    parser.add_argument("--version", required=True, help="release tag, for example v0.2.0")
    parser.add_argument("--sums", help="SHA256SUMS path or URL (default: the release's SHA256SUMS)")
    parser.add_argument("--out", required=True, help="tap directory; the formula goes to Formula/")
    parser.add_argument("--repo", default=DEFAULT_REPO, help=f"GitHub repository (default {DEFAULT_REPO})")
    parser.add_argument("--tap", default=DEFAULT_TAP, help=f"tap repository named in the README (default {DEFAULT_TAP})")
    parser.add_argument("--readme", action="store_true", help="also write README.md")
    args = parser.parse_args(argv)
    try:
        version = normalize_version(args.version)
        formula = render_formula(version, parse_sums(read_sums(args.sums, args.repo, version)), args.repo)
    except (FormulaError, OSError) as error:
        print(f"homebrew-formula: {error}", file=sys.stderr)
        return 1
    out = pathlib.Path(args.out)
    target = out / "Formula" / f"{NAME}.rb"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(formula, encoding="utf-8")
    print(f"wrote {target}")
    if args.readme:
        (out / "README.md").write_text(render_readme(args.tap, args.repo), encoding="utf-8")
        print(f"wrote {out / 'README.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
