#!/usr/bin/env python3
"""Copy clio's bundled web-to-mobile conversion data into internal/mobileguide, byte for byte.

clio ships WebToMobilePageConversionRules.json as an EmbeddedResource; get-mobile-page-conversion-guide
falls back to it when the rules CDN file cannot be read. The Go port embeds the same bytes. This script is
the only way the file gets into the repo: it copies it and records its SHA-256 in a generated Go file that
the Go test checks against the embedded bytes.

    python3 scripts/generate-mobile-conversion-rules.py --clio-source ~/.cache/creatio-mcp-go/clio-8.1.0.142
    python3 scripts/generate-mobile-conversion-rules.py --clio-source <checkout> --check   # verify only
"""
import argparse, hashlib, pathlib, subprocess, sys

REPO = pathlib.Path(__file__).resolve().parent.parent
TARGET_DIR = REPO / "internal/mobileguide/data"
SUM_FILE = REPO / "internal/mobileguide/rules_data_sum.go"
FILES = {
    # clio source path (relative to the checkout) -> file name under internal/mobileguide/data
    "clio/Command/McpServer/Data/WebToMobilePageConversionRules.json": "WebToMobilePageConversionRules.json",
}


def go_source(sums):
    lines = [
        "// Code generated by scripts/generate-mobile-conversion-rules.py. DO NOT EDIT.",
        "",
        "package mobileguide",
        "",
        "// bundledDataSHA256 maps each embedded data file to the SHA-256 of clio's bundled copy.",
        "var bundledDataSHA256 = map[string]string{",
    ]
    for name, digest in sorted(sums.items()):
        lines.append(f'\t"{name}": "{digest}",')
    lines += ["}", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--clio-source", required=True, type=pathlib.Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    sums, stale = {}, []
    for source_rel, name in FILES.items():
        data = (args.clio_source / source_rel).read_bytes()
        sums[name] = hashlib.sha256(data).hexdigest()
        target = TARGET_DIR / name
        if args.check:
            if not target.exists() or target.read_bytes() != data:
                stale.append(str(target))
        else:
            TARGET_DIR.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
    source = go_source(sums)
    if args.check:
        if not SUM_FILE.exists() or SUM_FILE.read_text() != source:
            stale.append(str(SUM_FILE))
        if stale:
            print("stale: " + ", ".join(stale), file=sys.stderr)
            return 1
        return 0
    SUM_FILE.write_text(source)
    subprocess.run(["gofmt", "-w", str(SUM_FILE)], check=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
