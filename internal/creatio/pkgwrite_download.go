// pkgWriteDownloadInfo is DownloadInfo.
type pkgWriteDownloadInfo struct {
	route, archiveName, destination, requestData string
}

// pkgWriteUnpackGzip is CompressionUtilities.UnpackFromGZip: every entry of clio's archive under target.
func pkgWriteUnpackGzip(archivePath, target string) error {
	file, err := os.Open(archivePath)
	if err != nil {
		return err
	}
	defer file.Close()
	reader, err := gzip.NewReader(file)
	if err != nil {
		return err
	}
	data, err := io.ReadAll(reader)
	if err != nil {
		return err
	}
	base, err := filepath.Abs(target)
	if err != nil {
		return err
	}
	for position := 0; len(data)-position >= 4; {
		nameLength := int(int32(binary.LittleEndian.Uint32(data[position:])))
		position += 4
		if nameLength <= 0 || nameLength*2 > len(data)-position {
			return nil
		}
		units := make([]uint16, nameLength)
		for index := range units {
			units[index] = binary.LittleEndian.Uint16(data[position+2*index:])
		}
		position += 2 * nameLength
		if len(data)-position < 4 {
			return errors.New("Unable to read beyond the end of the stream.")
		}
		contentLength := int(int32(binary.LittleEndian.Uint32(data[position:])))
		position += 4
		if contentLength < 0 || contentLength > len(data)-position {
			return errors.New("Unable to read beyond the end of the stream.")
		}
		name := strings.ReplaceAll(string(utf16.Decode(units)), `\`, "/")
		destination := filepath.Join(base, filepath.FromSlash(name))
		if !strings.HasPrefix(destination, base+string(os.PathSeparator)) {
			return fmt.Errorf("archive entry '%s' would be written outside '%s'", name, target)
		}
		if err := os.MkdirAll(filepath.Dir(destination), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(destination, data[position:position+contentLength], 0o644); err != nil {
			return err
		}
		position += contentLength
	}
	return nil
}

// pkgWriteCreateOrClear is FileSystem.CreateOrClearDirectory.
func pkgWriteCreateOrClear(directory string) error {
	if pkgWriteIsDirectory(directory) {
		entries, err := os.ReadDir(directory)
		if err != nil {
			return err
		}
		for _, entry := range entries {
			if err := os.RemoveAll(filepath.Join(directory, entry.Name())); err != nil {
				return err
			}
		}
		return nil
	}
	return os.MkdirAll(directory, 0o755)
}

// pkgWriteDownloadTimeout is Creatio.Client.DownloadFile's default request timeout.
var pkgWriteDownloadTimeout = 100 * time.Second

// pkgWriteDownloadFile is Creatio.Client.DownloadFile: a POST of requestData (an empty JSON body when there is
// none); a 2xx answer is saved to path, any other status fails as WebException does.
func (c *Client) pkgWriteDownloadFile(ctx context.Context, route, path, requestData string) error {
	response, err := c.serviceRequest(ctx, serviceCall{Route: route, Body: []byte(requestData), Timeout: pkgWriteDownloadTimeout, Limit: 1 << 30})
	if err != nil {
		return err
	}
	if response.status < 200 || response.status >= 300 {
		return fmt.Errorf("The remote server returned an error: (%d) %s.", response.status, http.StatusText(response.status))
	}
	return os.WriteFile(path, response.payload, 0o644)
}

// pkgWriteCsprojReference is the part of a csproj Reference the dll download reads.
type pkgWriteCsprojReference struct {
	packageName, hintPath string
}

// pkgWriteCsprojReferences is CsprojFile.GetPackageReferences: the References of the ItemGroup labelled
// "Package References", Terrasoft.Configuration left out. A Reference without SpecificVersion or Private
// fails as bool.Parse("") does.
func pkgWriteCsprojReferences(content string) ([]pkgWriteCsprojReference, error) {
	if content == "" {
		return nil, nil
	}
	var project struct {
		Groups []struct {
			Attrs      []xml.Attr `xml:",any,attr"`
			References []struct {
				Include         string  `xml:"Include,attr"`
				HintPath        *string `xml:"HintPath"`
				SpecificVersion *string `xml:"SpecificVersion"`
				Private         *string `xml:"Private"`
			} `xml:"Reference"`
		} `xml:"ItemGroup"`
	}
	if err := xml.Unmarshal([]byte(content), &project); err != nil {
		return nil, err
	}
	for _, group := range project.Groups {
		if len(group.Attrs) == 0 || xmlLocalName(group.Attrs[0].Name) != "Label" || group.Attrs[0].Value != "Package References" {
			continue
		}
		var references []pkgWriteCsprojReference
		for _, reference := range group.References {
			if reference.Include == "" || reference.Include == "Terrasoft.Configuration" {
				continue
			}
			for _, flag := range []*string{reference.SpecificVersion, reference.Private} {
				text := ""
				if flag != nil {
					text = strings.TrimSpace(*flag)
				}
				if !strings.EqualFold(text, "true") && !strings.EqualFold(text, "false") {
					return nil, fmt.Errorf("String '%s' was not recognized as a valid Boolean.", text)
				}
			}
			hint := ""
			if reference.HintPath != nil {
				hint = *reference.HintPath
			}
			references = append(references, pkgWriteCsprojReference{packageName: reference.Include, hintPath: hint})
		}
		return references, nil
	}
	return nil, errors.New("Object reference not set to an instance of an object.")
}

// pkgWriteDownloadAll is Downloader.Download: every archive fetched and unpacked in parallel, as clio does
// (the "Run download" lines therefore come in no fixed order).
func (c *Client) pkgWriteDownloadAll(ctx context.Context, infos []pkgWriteDownloadInfo, log *appWriteLog) error {
	temporary, err := os.MkdirTemp("", "clio-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(temporary)
	var wait sync.WaitGroup
	errs := make([]error, len(infos))
	for index, info := range infos {
		wait.Add(1)
		go func() {
			defer wait.Done()
			archive := filepath.Join(temporary, info.archiveName+".gz")
			log.line("Run download " + info.archiveName)
			if err := c.pkgWriteDownloadFile(ctx, info.route, archive, info.requestData); err != nil {
				errs[index] = err
				return
			}
			if err := pkgWriteCreateOrClear(info.destination); err != nil {
				errs[index] = err
				return
			}
			if err := pkgWriteUnpackGzip(archive, info.destination); err != nil {
				errs[index] = err
				return
			}
			_ = os.Remove(archive)
		}()
	}
	wait.Wait()
	var messages []string
	for _, err := range errs {
		if err != nil {
			messages = append(messages, "("+err.Error()+")")
		}
	}
	if len(messages) > 0 {
		return errors.New("One or more errors occurred. " + strings.Join(messages, " "))
	}
	return nil
}

// pkgWriteDownloadPackageDlls is Downloader.DownloadPackageDll for every reference; a failure is a warning.
func (c *Client) pkgWriteDownloadPackageDlls(ctx context.Context, infos []pkgWriteDownloadInfo, log *appWriteLog) {
	temporary, err := os.MkdirTemp("", "clio-")
	if err != nil {
		log.warning(err.Error())
		return
	}
	defer os.RemoveAll(temporary)
	var wait sync.WaitGroup
	for _, info := range infos {
		wait.Add(1)
		go func() {
			defer wait.Done()
			if strings.TrimSuffix(info.archiveName, filepath.Ext(info.archiveName)) == "" {
				log.warning("Packages name is empty, skip download " + c.serviceURL(info.route))
				return
			}
			archive := filepath.Join(temporary, info.archiveName)
			if err := c.pkgWriteDownloadFile(ctx, info.route, archive, info.requestData); err != nil {
				log.warning(err.Error() + pkgWriteNewLine())
				return
			}
			if stat, err := os.Stat(archive); err == nil && stat.Size() == 0 {
				log.warning(fmt.Sprintf("File: %s is empty", info.archiveName))
			} else {
				if err := os.MkdirAll(filepath.Dir(info.destination), 0o755); err != nil {
					log.warning(err.Error() + pkgWriteNewLine())
					return
				}
				log.info("Run download - OK: " + info.archiveName)
				if err := pkgWriteCopyFile(archive, info.destination); err != nil {
					log.warning(err.Error() + pkgWriteNewLine())
				}
			}
			_ = os.Remove(archive)
		}()
	}
	wait.Wait()
}

// pkgWriteCliogateCompatible is ClioGateway.IsCompatibleWith over the installed package list.
func pkgWriteCliogateCompatible(packages []pkgWriteInstalledPackage, minimum string) bool {
	required, _ := pkgWriteParsePackageVersion(minimum)
	var lowest *pkgWritePackageVersion
	for _, item := range packages {
		if !strings.EqualFold(item.Name, "cliogate") && !strings.EqualFold(item.Name, "cliogate_netcore") {
			continue
		}
		if version, ok := pkgWriteParsePackageVersion(item.Version); ok && (lowest == nil || version.compare(*lowest) < 0) {
			copied := version
			lowest = &copied
		}
	}
	return lowest != nil && lowest.compare(required) >= 0
}

// pkgWriteApplicationDownload is ApplicationDownloader.Download for the workspace's packages.
func (c *Client) pkgWriteApplicationDownload(ctx context.Context, workspace pkgWriteWorkspace, packageNames []string, log *appWriteLog) error {
	installed, err := c.pkgWriteInstalledPackages(ctx)
	if err != nil {
		return err
	}
	if !pkgWriteCliogateCompatible(installed, "2.0.0.0") {
		log.warning("Downloading of core libraries requires " + pkgWriteYellow("cliogate") + " version 2.0.0.0 or higher.")
		return nil
	}
	infos := []pkgWriteDownloadInfo{
		{route: "rest/CreatioApiGateway/GetCoreBinFolder", archiveName: "CoreBin", destination: workspace.coreBin()},
		{route: "rest/CreatioApiGateway/GetConfigurationLibFolder", archiveName: "Lib", destination: workspace.lib()},
		{route: "rest/CreatioApiGateway/GetConfigurationBinFolder", archiveName: "ConfigurationBin", destination: workspace.confBin()},
	}
	for _, name := range packageNames {
		safe := strings.ReplaceAll(strings.ReplaceAll(name, " ", ""), ",", `","`)
		infos = append(infos, pkgWriteDownloadInfo{route: "rest/CreatioApiGateway/GetAutogeneratedFolder", archiveName: "Autogenerated." + name,
			destination: filepath.Join(workspace.packagePath(name), "Autogenerated"), requestData: `"` + safe + `"`})
	}
	if err := c.pkgWriteDownloadAll(ctx, infos, log); err != nil {
		return err
	}
	if pkgWriteCliogateCompatible(installed, "2.0.0.29") {
		dlls, err := pkgWriteReferencedDlls(workspace, packageNames)
		if err != nil {
			return err
		}
		if len(dlls) > 0 {
			c.pkgWriteDownloadPackageDlls(ctx, dlls, log)
		}
	} else {
		log.warning("Downloading of referenced package dlls requires " + pkgWriteYellow("cliogate") + " version 2.0.0.29 or higher.")
	}
	if err := os.MkdirAll(filepath.Join(workspace.applicationFolder(), "packages"), 0o755); err != nil {
		return err
	}
	for _, name := range packageNames {
		schemas := filepath.Join(workspace.packagePath(name), "Schemas")
		_ = filepath.WalkDir(schemas, func(path string, entry os.DirEntry, err error) error {
			if err != nil || entry.IsDir() || !strings.EqualFold(filepath.Ext(path), ".cs") {
				return nil
			}
			base := strings.TrimSuffix(filepath.Base(path), filepath.Ext(path))
			_ = os.Remove(filepath.Join(workspace.packagePath(name), "Autogenerated", "Src", base+"."+name+".cs"))
			return nil
		})
	}
	return nil
}

// pkgWriteReferencedDlls is ApplicationDownloader.GetDownloadInfoFromCsProj.
func pkgWriteReferencedDlls(workspace pkgWriteWorkspace, packageNames []string) ([]pkgWriteDownloadInfo, error) {
	if len(packageNames) == 0 {
		return nil, nil
	}
	seen := map[string]bool{}
	var infos []pkgWriteDownloadInfo
	application := workspace.applicationFolder()
	for _, name := range packageNames {
		content, _ := os.ReadFile(filepath.Join(workspace.root, "packages", name, "Files", name+".csproj"))
		references, err := pkgWriteCsprojReferences(string(content))
		if err != nil {
			return nil, err
		}
		for _, reference := range references {
			if seen[reference.packageName] {
				continue
			}
			seen[reference.packageName] = true
			parts := strings.Split(reference.hintPath, "/")
			dll := parts[len(parts)-1]
			var destination string
			switch {
			case strings.Contains(application, "net-core"):
				destination = filepath.Join(application, "packages", reference.packageName, "Files", "Bin", "netstandard", dll)
			case strings.Contains(application, "net-framework"):
				destination = filepath.Join(application, "packages", reference.packageName, "Files", "Bin", dll)
			}
			payload, _ := json.Marshal(struct {
				PackageName string `json:"packageName"`
				DllName     string `json:"dllName"`
			}{reference.packageName, dll})
			infos = append(infos, pkgWriteDownloadInfo{route: "rest/CreatioApiGateway/DownloadFile", archiveName: dll,
				destination: destination, requestData: string(payload)})
		}
	}
	return infos, nil
}

// pkgWriteWorkspacePackages reads WorkspaceSettings.Packages from .clio/workspaceSettings.json.
func pkgWriteWorkspacePackages(workspace pkgWriteWorkspace) ([]string, error) {
	path := workspace.settingsPath()
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("Json file not found by path: '%s'", path)
	}
	var raw map[string]json.RawMessage
	if err := json.Unmarshal(bytes.TrimPrefix(data, []byte{0xEF, 0xBB, 0xBF}), &raw); err != nil {
		return nil, err
	}
	keys := make([]string, 0, len(raw))
	for key := range raw {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	for _, key := range keys {
		if strings.EqualFold(key, "Packages") {
			var packages []string
			if err := json.Unmarshal(raw[key], &packages); err != nil {
				return nil, err
			}
			return packages, nil
		}
	}
	return []string{}, nil
}

// DownloadConfigurationFromEnvironment is DownloadConfigurationCommand.DownloadFromNamedEnv: from the
// environment's EnvironmentPath when it is a local directory, otherwise from the environment through cliogate.
func (c *Client) DownloadConfigurationFromEnvironment(ctx context.Context, workspacePath, environmentName, environmentPath string) CommandResult {
	log := &appWriteLog{}
	workspace := pkgWriteOpenWorkspace(workspacePath, c.config.IsNetCore)
	failed := func(err error) CommandResult {
		log.error("Error: " + err.Error())
		log.error(err.Error())
		return log.result(1)
	}
	if strings.TrimSpace(environmentPath) != "" && pkgWriteIsDirectory(environmentPath) {
		if err := pkgWriteDownloadFromPath(workspace, environmentPath, log); err != nil {
			return failed(err)
		}
		log.line(fmt.Sprintf("Download from %s path completed successfully", environmentPath))
		return log.result(0)
	}
	packages, err := pkgWriteWorkspacePackages(workspace)
	if err != nil {
		return failed(err)
	}
	if err := c.pkgWriteApplicationDownload(ctx, workspace, packages, log); err != nil {
		return failed(err)
	}
	log.line(fmt.Sprintf("Download from %s environment completed successfully", environmentName))
	return log.result(0)
}
