package creatio

// download-configuration-by-build and -by-environment: clio's DownloadConfigurationCommand. Both fill a
// workspace's .application folder (core-bin, Lib, bin, packages) with the Creatio assemblies a workspace
// builds against:
//
//   - from a build (ZipBasedApplicationDownloader): a Creatio zip, extracted to a temporary folder, or an
//     extracted directory - a local copy, nothing is sent to Creatio;
//   - from an environment: from its EnvironmentPath when that is a local directory, otherwise from the
//     environment itself through cliogate (ApplicationDownloader): CoreBin, Lib, ConfigurationBin and each
//     workspace package's Autogenerated folder as clio .gz archives, and the dlls the packages' projects
//     reference. That reads the environment and changes only local files.
//
// clio runs the command with the process working directory set to the workspace; here the workspace path is
// passed in, and the workspace root is looked for from it upwards (the folder holding .clio).

