// pkgWriteWorkspace is WorkspacePathBuilder over a given current directory.
type pkgWriteWorkspace struct {
	current, root string
	netCore       bool
}

func pkgWriteOpenWorkspace(current string, netCore bool) pkgWriteWorkspace {
	root := current
	for directory := current; ; {
		if info, err := os.Stat(filepath.Join(directory, ".clio")); err == nil && info.IsDir() {
			root = directory
			break
		}
		parent := filepath.Dir(directory)
		if parent == directory {
			break
		}
		directory = parent
	}
	return pkgWriteWorkspace{current: current, root: root, netCore: netCore}
}

func (w pkgWriteWorkspace) settingsPath() string {
	return filepath.Join(w.root, ".clio", "workspaceSettings.json")
}

func (w pkgWriteWorkspace) isWorkspace() bool {
	info, err := os.Stat(w.settingsPath())
	return err == nil && !info.IsDir()
}

func (w pkgWriteWorkspace) applicationFolder() string {
	if w.netCore {
		return filepath.Join(w.root, ".application", "net-core")
	}
	return filepath.Join(w.root, ".application", "net-framework")
}

func (w pkgWriteWorkspace) coreBin() string { return filepath.Join(w.applicationFolder(), "core-bin") }
func (w pkgWriteWorkspace) lib() string     { return filepath.Join(w.applicationFolder(), "Lib") }
func (w pkgWriteWorkspace) confBin() string { return filepath.Join(w.applicationFolder(), "bin") }

func (w pkgWriteWorkspace) packagePath(name string) string {
	if w.isWorkspace() {
		return filepath.Join(w.root, "packages", name)
	}
	return filepath.Join(w.current, name)
}

// ---- from a build (ZipBasedApplicationDownloader) ----

func pkgWriteFiles(directory string) []string {
	entries, _ := os.ReadDir(directory)
	var files []string
	for _, entry := range entries {
		if !entry.IsDir() {
			files = append(files, filepath.Join(directory, entry.Name()))
		}
	}
	return files
}

func pkgWriteDirectories(directory string) []string {
	entries, _ := os.ReadDir(directory)
	var directories []string
	for _, entry := range entries {
		if entry.IsDir() {
			directories = append(directories, filepath.Join(directory, entry.Name()))
		}
	}
	return directories
}

func pkgWriteIsDirectory(path string) bool {
	info, err := os.Stat(path)
	return err == nil && info.IsDir()
}

func pkgWriteIsFile(path string) bool {
	info, err := os.Stat(path)
	return err == nil && !info.IsDir()
}

func pkgWriteCopyFile(source, target string) error {
	data, err := os.ReadFile(source)
	if err != nil {
		return err
	}
	return os.WriteFile(target, data, 0o644)
}

func pkgWriteCopyAll(source, target string) error {
	for _, file := range pkgWriteFiles(source) {
		if err := pkgWriteCopyFile(file, filepath.Join(target, filepath.Base(file))); err != nil {
			return err
		}
	}
	return nil
}

func pkgWriteCopyTree(source, target string) error {
	if err := os.MkdirAll(target, 0o755); err != nil {
		return err
	}
	if err := pkgWriteCopyAll(source, target); err != nil {
		return err
	}
	for _, directory := range pkgWriteDirectories(source) {
		if err := pkgWriteCopyTree(directory, filepath.Join(target, filepath.Base(directory))); err != nil {
			return err
		}
	}
	return nil
}

// pkgWriteBuildCopier is ZipBasedApplicationDownloader's copy steps for one extracted build.
type pkgWriteBuildCopier struct {
	workspace pkgWriteWorkspace
	log       *appWriteLog
}

func (b pkgWriteBuildCopier) rootAssemblies(extracted, destination string, netCore bool) error {
	source := extracted
	if !netCore {
		source = filepath.Join(extracted, "Terrasoft.WebApp", "bin")
	}
	// clio checks the count before the loop, so this warning is always written.
	b.log.warning("No root assemblies found in " + extracted)
	copied := 0
	for _, file := range pkgWriteFiles(source) {
		extension := strings.ToLower(filepath.Ext(file))
		if extension == ".dll" || extension == ".pdb" {
			if err := pkgWriteCopyFile(file, filepath.Join(destination, filepath.Base(file))); err != nil {
				return err
			}
			copied++
		}
	}
	b.log.info(fmt.Sprintf("Copied %d root assemblies (DLL and PDB files)", copied))
	return nil
}

func (b pkgWriteBuildCopier) configurationBin(extracted, destination string, netCore bool) error {
	confBin := filepath.Join(extracted, "conf", "bin")
	if !netCore {
		confBin = filepath.Join(extracted, "Terrasoft.WebApp", "conf", "bin")
	}
	if !pkgWriteIsDirectory(confBin) {
		b.log.warning("Configuration bin directory not found: " + confBin)
		return nil
	}
	latest, latestNumber := "", -1
	for _, directory := range pkgWriteDirectories(confBin) {
		if number, err := strconv.Atoi(filepath.Base(directory)); err == nil && number > latestNumber {
			latest, latestNumber = directory, number
		}
	}
	if latest == "" {
		b.log.warning("No numbered folders found in " + confBin)
		return nil
	}
	framework := "NetCore"
	if !netCore {
		framework = "NetFramework"
	}
	b.log.info(fmt.Sprintf("Copying %s configuration bin files from %s to %s", framework, latest, destination))
	if err := os.MkdirAll(destination, 0o755); err != nil {
		return err
	}
	for _, name := range []string{"Terrasoft.Configuration.dll", "Terrasoft.Configuration.ODataEntities.dll"} {
		source := filepath.Join(latest, name)
		if !pkgWriteIsFile(source) {
			b.log.warning("File not found: " + source)
			continue
		}
		if err := pkgWriteCopyFile(source, filepath.Join(destination, name)); err != nil {
			return err
		}
		b.log.info("Copied " + name)
	}
	return nil
}

func (b pkgWriteBuildCopier) packages(extracted string, netCore bool) error {
	source := filepath.Join(extracted, "Terrasoft.Configuration", "Pkg")
	destinationRoot := filepath.Join(b.workspace.root, ".application", "net-core", "packages")
	framework := "NetCore"
	if !netCore {
		source = filepath.Join(extracted, "Terrasoft.WebApp", "Terrasoft.Configuration", "Pkg")
		destinationRoot = filepath.Join(b.workspace.root, ".application", "net-framework", "packages")
		framework = "NetFramework"
	}
	if !pkgWriteIsDirectory(source) {
		b.log.warning("Packages directory not found: " + source)
		return nil
	}
	if err := os.MkdirAll(destinationRoot, 0o755); err != nil {
		return err
	}
	for _, folder := range pkgWriteDirectories(source) {
		if !pkgWriteIsDirectory(filepath.Join(folder, "Files", "bin")) {
			continue
		}
		name := filepath.Base(folder)
		b.log.info(fmt.Sprintf("Copying %s package %s", framework, name))
		if err := pkgWriteCopyTree(folder, filepath.Join(destinationRoot, name)); err != nil {
			return err
		}
	}
	return nil
}

func (b pkgWriteBuildCopier) download(extracted string, netCore bool) error {
	from, to, framework := "net-framework", "net-core", "NetCore"
	if !netCore {
		from, to, framework = "net-core", "net-framework", "NetFramework"
	}
	b.log.info(fmt.Sprintf("Detected %s Creatio", framework))
	coreBin := strings.ReplaceAll(b.workspace.coreBin(), from, to)
	lib := strings.ReplaceAll(b.workspace.lib(), from, to)
	confBin := strings.ReplaceAll(b.workspace.confBin(), from, to)
	b.log.info(fmt.Sprintf("Copying %s root assemblies (DLL and PDB) to %s", framework, coreBin))
	if err := os.MkdirAll(coreBin, 0o755); err != nil {
		return err
	}
	if err := b.rootAssemblies(extracted, coreBin, netCore); err != nil {
		return err
	}
	if libSource := filepath.Join(extracted, "Terrasoft.Configuration", "Lib"); pkgWriteIsDirectory(libSource) {
		b.log.info(fmt.Sprintf("Copying %s lib files to %s", framework, lib))
		if err := os.MkdirAll(lib, 0o755); err != nil {
			return err
		}
		if err := pkgWriteCopyAll(libSource, lib); err != nil {
			return err
		}
	}
	if err := b.configurationBin(extracted, confBin, netCore); err != nil {
		return err
	}
	if err := b.packages(extracted, netCore); err != nil {
		return err
	}
	if !netCore {
		// CopyLibFiles, framework only: Terrasoft.WebApp/Terrasoft.Configuration/Lib to .application/net-framework/lib.
		source := filepath.Join(extracted, "Terrasoft.WebApp", "Terrasoft.Configuration", "Lib")
		destination := filepath.Join(b.workspace.root, ".application", "net-framework", "lib")
		if !pkgWriteIsDirectory(source) {
			b.log.warning("Source directory not found: " + source)
		} else {
			b.log.info(fmt.Sprintf("Copying lib files from %s to %s", source, destination))
			if err := os.MkdirAll(destination, 0o755); err != nil {
				return err
			}
			if err := pkgWriteCopyAll(source, destination); err != nil {
				return err
			}
		}
	}
	b.log.info(framework + " configuration downloaded successfully")
	return nil
}

func pkgWriteNotWorkspace() error {
	return errors.New("Current directory is not a workspace. Please run this command from a workspace directory.")
}

// pkgWriteDownloadFromPath is ZipBasedApplicationDownloader.DownloadFromPath; an error is what the command
// reports after the downloader's own lines.
func pkgWriteDownloadFromPath(workspace pkgWriteWorkspace, path string, log *appWriteLog) error {
	copier := pkgWriteBuildCopier{workspace: workspace, log: log}
	isFramework := func(directory string) bool { return pkgWriteIsDirectory(filepath.Join(directory, "Terrasoft.WebApp")) }
	if strings.EqualFold(filepath.Ext(path), ".zip") {
		if !pkgWriteIsFile(path) {
			return errors.New("Zip file not found: " + path)
		}
		if !workspace.isWorkspace() {
			return pkgWriteNotWorkspace()
		}
		log.info("Extracting Creatio from " + path)
		temporary, err := os.MkdirTemp("", "clio-")
		if err != nil {
			return err
		}
		defer os.RemoveAll(temporary)
		failed := func(err error) error {
			log.error("Error downloading configuration from zip: " + err.Error())
			return err
		}
		if err := pkgWriteUnzip(path, temporary); err != nil {
			return failed(err)
		}
		log.info("Extracted to temporary directory: " + temporary)
		if err := copier.download(temporary, !isFramework(temporary)); err != nil {
			return failed(err)
		}
		log.info("Configuration download from zip completed successfully")
		return nil
	}
	if !pkgWriteIsDirectory(path) {
		return errors.New("Directory not found: " + path)
	}
	if !workspace.isWorkspace() {
		return pkgWriteNotWorkspace()
	}
	log.info("Processing Creatio configuration from directory: " + path)
	if err := copier.download(path, !isFramework(path)); err != nil {
		log.error("Error downloading configuration from directory: " + err.Error())
		return err
	}
	log.info("Configuration download from directory completed successfully")
	return nil
}

// pkgWriteUnzip is ZipFile.ExtractToDirectory; an entry that would land outside the target is refused.
func pkgWriteUnzip(archive, target string) error {
	reader, err := zip.OpenReader(archive)
	if err != nil {
		return err
	}
	defer reader.Close()
	base, err := filepath.Abs(target)
	if err != nil {
		return err
	}
	for _, file := range reader.File {
		destination := filepath.Join(base, filepath.FromSlash(strings.ReplaceAll(file.Name, `\`, "/")))
		if destination != base && !strings.HasPrefix(destination, base+string(os.PathSeparator)) {
			return fmt.Errorf("Extracting Zip entry would have resulted in a file outside the specified destination directory.")
		}
		if file.FileInfo().IsDir() || strings.HasSuffix(file.Name, "/") {
			if err := os.MkdirAll(destination, 0o755); err != nil {
				return err
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(destination), 0o755); err != nil {
			return err
		}
		source, err := file.Open()
		if err != nil {
			return err
		}
		data, readErr := io.ReadAll(source)
		source.Close()
		if readErr != nil {
			return readErr
		}
		if err := os.WriteFile(destination, data, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// DownloadConfigurationFromBuild is DownloadConfigurationCommand.Execute with a build path: a local copy.
func DownloadConfigurationFromBuild(workspacePath, buildPath string) CommandResult {
	log := &appWriteLog{}
	if err := pkgWriteDownloadFromPath(pkgWriteOpenWorkspace(workspacePath, false), buildPath, log); err != nil {
		log.error(err.Error())
		return log.result(1)
	}
	return log.result(0)
}

