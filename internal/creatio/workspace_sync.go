package creatio

// The Creatio side of push-workspace and restore-workspace, as clio 8.1.0.142 sends it:
//
//   - push: WorkspaceInstaller's ResetSchemaChangeState per package, then ApplicationInstaller over
//     BasePackageInstaller.InstallPackedPackage for the CreatioPackages.zip archive — DesignNodeSessionGuard's
//     session-start request, the 1 MB chunk upload, the optional backup, AppInstallerService InstallAppFromFile
//     while the installation log is followed every 3 s, InstallLogAnalyzer's verdict, the developer-mode unlock
//     and the restart;
//   - restore: ApplicationPing, PackageDownloader's GetZipPackages download and Downloader's
//     GetAutogeneratedFolder download.
//
// Requests clio sends through Creatio.Client's ExecutePostRequest keep its semantics: the body is read whatever
// the HTTP status, and only a request that got no answer fails.

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"strings"
	"time"
)

// CommandLog receives a command's execution-log messages in clio's order (workspace.Log implements it).
type CommandLog interface {
	Line(value string)
	Info(value string)
	Warning(value string)
	Error(value string)
}

// WorkspaceInstallRequest is what ApplicationInstaller.Install reads for one workspace archive.
type WorkspaceInstallRequest struct {
	// ArchivePath is the CreatioPackages.zip file.
	ArchivePath  string
	CreateBackup bool
	// EnvironmentURI is EnvironmentSettings.Uri, which the installer logs.
	EnvironmentURI string
	// DeveloperMode is EnvironmentSettings.DeveloperModeEnabled.
	DeveloperMode bool
}

// WorkspaceInvalidArchive is InvalidGZipArchiveInstallException: the installation service rejected the archive.
type WorkspaceInvalidArchive struct{ Message string }

func (e WorkspaceInvalidArchive) Error() string { return e.Message }

const (
	// workspaceSyncPostTimeout is ExecutePostRequest's default timeout (10 s).
	workspaceSyncPostTimeout = 10 * time.Second
	// workspaceSyncDownloadTimeout is DownloadFile's default timeout (100 s).
	workspaceSyncDownloadTimeout = 100 * time.Second
	// workspaceSyncDownloadLimit bounds a downloaded archive; clio sets none.
	workspaceSyncDownloadLimit = 2 << 30

	workspaceSyncStickySession = "StickySession"
)

// workspaceSyncFault words a failed request as Creatio.Client raises it: a request that got no answer is the
// socket's text, which ExecutePostRequest (a blocking .Result) wraps in an AggregateException; a timeout is the
// cancelled task. A login failure keeps its own text, as clio's login step raises before the request.
func workspaceSyncFault(err error, aggregate bool) error {
	if err == nil || isLoginError(err) {
		if fault, ok := asConnectFault(err); ok {
			return errors.New(fault.Error())
		}
		return err
	}
	message := err.Error()
	if fault := newConnectFault(err); fault != nil {
		message = fault.Error()
	} else if errors.Is(err, context.DeadlineExceeded) {
		message = "A task was canceled."
	}
	if aggregate {
		message = "One or more errors occurred. (" + message + ")"
	}
	return errors.New(message)
}

// workspaceSyncPost is ExecutePostRequest: the body whatever the status.
func (c *Client) workspaceSyncPost(ctx context.Context, route, body string, timeout time.Duration) ([]byte, error) {
	response, err := c.serviceRequest(ctx, serviceCall{Route: route, Body: []byte(body), Timeout: timeout})
	if err != nil {
		return nil, workspaceSyncFault(err, true)
	}
	return response.payload, nil
}

// ResetSchemaChangeState is WorkspaceInstaller.ResetSchemaChangeStateServiceUrlByPackage (ClioGate); the
// answer is not read.
func (c *Client) ResetSchemaChangeState(ctx context.Context, packageName string) error {
	_, err := c.workspaceSyncPost(ctx, "rest/CreatioApiGateway/ResetSchemaChangeState", `{"packageName":"`+packageName+`"}`,
		workspaceSyncPostTimeout)
	return err
}

// InstallWorkspaceArchive is ApplicationInstaller.Install over BasePackageInstaller.InternalInstall for an
// archive that exists: false when the installation did not succeed (logged, not raised, as clio returns it);
// an error for what clio raises (a transport failure, an invalid archive, a web farm this server cannot route).
func (c *Client) InstallWorkspaceArchive(ctx context.Context, request WorkspaceInstallRequest, log CommandLog) (bool, error) {
	if err := c.workspaceSyncStartSession(ctx, log); err != nil {
		return false, err
	}
	log.Line("Uploading...")
	fileName := filepath.Base(request.ArchivePath)
	if err := c.appWriteUpload(ctx, request.ArchivePath); err != nil {
		return false, workspaceSyncFault(err, false)
	}
	log.Line("Uploaded")
	code := strings.Split(fileName, ".")[0]
	log.Info(request.EnvironmentURI)
	if request.CreateBackup {
		log.Line("Backup process...")
		backup := `{"Name":"` + code + `","Code":"` + code + `","ZipPackageName":"` + fileName + `","LastUpdate":0}`
		if _, err := c.workspaceSyncPost(ctx, "ServiceModel/PackageInstallerService.svc/CreatePackageBackup", backup,
			workspaceSyncPostTimeout); err != nil {
			return false, nil // "Dont created backup."; with no report path the text goes nowhere
		}
		log.Line("Backup completed")
	} else {
		log.Info("Package backup skipped.")
	}
	success, err := c.workspaceSyncInstallWithLog(ctx, fileName, code, log)
	if err != nil {
		return false, err
	}
	if request.DeveloperMode {
		if err := c.workspaceSyncUnlock(ctx); err != nil {
			return false, err
		}
	}
	if success && (request.DeveloperMode || c.config.IsNetCore) {
		log.Line("Restart application...")
		route := "ServiceModel/AppInstallerService.svc/UnloadAppDomain"
		if c.config.IsNetCore {
			route = "ServiceModel/AppInstallerService.svc/RestartApp"
		}
		if _, err := c.workspaceSyncPost(ctx, route, "{}", appWriteInstallTimings.installTimeout); err != nil {
			log.Line("Error while restarting application: " + err.Error())
		}
	}
	return success, nil
}

// workspaceSyncStartSession is DesignNodeSessionGuard.Prepare: the first authenticated request of the
// installation session. A web farm issues StickySession in its answer; clio then confirms the design node and
// keeps the cookie on every later request, which this client cannot do, so the installation is refused there
// before anything is uploaded.
func (c *Client) workspaceSyncStartSession(ctx context.Context, log CommandLog) error {
	requestCtx, cancel := context.WithTimeout(ctx, workspaceSyncDownloadTimeout)
	defer cancel()
	response, _, err := c.doAuthenticated(requestCtx, c.requestClient(), func() (*http.Request, error) {
		request, err := http.NewRequestWithContext(requestCtx, http.MethodPost,
			c.serviceURL("ServiceModel/UserInfoService.svc/GetCurrentUserInfo"), strings.NewReader("{}"))
		if err != nil {
			return nil, err
		}
		request.Header.Set("Content-Type", "application/json")
		return request, nil
	})
	if err != nil {
		return workspaceSyncFault(err, false)
	}
	_, _ = io.Copy(io.Discard, io.LimitReader(response.Body, maxResponseBytes))
	response.Body.Close()
	if response.StatusCode < 200 || response.StatusCode >= 300 {
		log.Warning(fmt.Sprintf("The request that starts the installation session answered HTTP %d. If this environment is a "+
			"web farm, the installation may not reach its design node.", response.StatusCode))
	}
	for _, cookie := range response.Cookies() {
		if cookie.Name == workspaceSyncStickySession {
			return errors.New("The installation session does not reach the design node of the web farm: the environment " +
				"issued the StickySession cookie, and this server cannot keep it on the upload and installation " +
				"requests. Nothing was uploaded: on a web farm packages are installed only on the design node. " +
				"Push this workspace with clio.")
		}
	}
	return nil
}

// workspaceSyncInstallRequest is InstallAppRequest as System.Text.Json writes it (CheckCompilationErrors null,
// so left out).
type workspaceSyncInstallRequest struct {
	Name             string `json:"Name"`
	Code             string `json:"Code"`
	ZipPackageName   string `json:"ZipPackageName"`
	LastUpdateString int    `json:"LastUpdateString"`
}

// workspaceSyncInstallWithLog is InstallPackageOnServerWithLogListener with FailOnError off.
func (c *Client) workspaceSyncInstallWithLog(ctx context.Context, fileName, code string, log CommandLog) (bool, error) {
	log.Line("Install " + fileName + " ...")
	log.Line("Installation log:")
	initial := c.appWriteInstallLog(ctx)
	listenCtx, stop := context.WithCancel(ctx)
	listened := initial
	done := make(chan struct{})
	go func() {
		defer close(done)
		current := initial
		for listenCtx.Err() == nil {
			complete := c.appWriteInstallLog(listenCtx)
			if output := appWriteLogDiff(current, complete); strings.TrimSpace(output) != "" {
				log.Line(output)
				current = complete
			}
			appWriteSleep(listenCtx, appWriteInstallTimings.logInterval)
		}
		listened = current
	}()
	body, _ := json.Marshal(workspaceSyncInstallRequest{Name: code, Code: code, ZipPackageName: fileName})
	payload, err := c.workspaceSyncPost(ctx, "ServiceModel/AppInstallerService.svc/InstallAppFromFile", string(body),
		appWriteInstallTimings.installTimeout)
	stop()
	<-done
	if err != nil {
		return false, err
	}
	response, err := workspaceSyncParseResponse(payload)
	if err != nil {
		return false, err
	}
	complete := c.appWriteInstallLog(ctx)
	current := appWriteLogDiff(initial, complete)
	log.Line(appWriteLogDiff(listened, complete))
	success := response == nil || response.Success
	workspaceSyncReportLocallyModified(current, log)
	if !success && appWriteInvalidGzip(response, current) {
		message := "The package archive is invalid or corrupted."
		if response != nil && response.ErrorInfo != nil && response.ErrorInfo.Message != "" {
			message = response.ErrorInfo.Message
		} else if line := appWriteInvalidGzipLine(current); line != "" {
			message = line
		}
		return false, WorkspaceInvalidArchive{Message: message}
	}
	if !success {
		if initial == "" || !strings.HasPrefix(complete, initial) {
			log.Warning("The installation log could not be attributed to this run, so the reported failure is " +
				"kept. Re-run the command to get a usable log.")
		} else if appWriteTreatAsSuccess(response, current) {
			log.Warning("The installation service reported a failure, but the installation finished and the only " +
				"problem reported in this run's log was a locally modified schema. Treating the " +
				"installation as successful.")
			success = true
		}
	}
	if !success {
		log.Error("Package installation failed: " + appWriteDescribeFailure(response, current))
	}
	return success, nil
}

// workspaceSyncParseResponse is JsonConvert.DeserializeObject<BaseResponse>: an empty answer is null, an answer
// that is not JSON fails with Json.NET's text for its first character.
func workspaceSyncParseResponse(payload []byte) (*appWriteInstallResponse, error) {
	trimmed := bytes.TrimSpace(payload)
	if len(trimmed) == 0 {
		return nil, nil
	}
	var response *appWriteInstallResponse
	if err := json.Unmarshal(trimmed, &response); err != nil {
		first := []rune(string(trimmed))[0]
		if first != '{' && first != '[' && first != 'n' {
			return nil, fmt.Errorf("Unexpected character encountered while parsing value: %c. Path '', line 0, position 0.", first)
		}
		return nil, fmt.Errorf("Error reading the installation service answer: %s", err.Error())
	}
	return response, nil
}

// workspaceSyncReportLocallyModified is ReportLocallyModifiedSchemas.
func workspaceSyncReportLocallyModified(current string, log CommandLog) {
	collected := &appWriteLog{}
	appWriteReportLocallyModified(current, collected)
	for _, message := range collected.result(0).Messages {
		log.Warning(message.Value)
	}
}

// workspaceSyncUnlock is PackageLockManager.Unlock() through ClioGate, read as clio reads it: the body whatever
// the status.
func (c *Client) workspaceSyncUnlock(ctx context.Context) error {
	const route = "UnlockPackages"
	payload, err := c.workspaceSyncPost(ctx, "rest/CreatioApiGateway/UnlockPackages", `{"unlockPackages":null}`, workspaceSyncPostTimeout)
	if err != nil {
		return err
	}
	if len(payload) == 0 {
		return fmt.Errorf("ClioGate %s returned an empty response. Check the Creatio application logs (Error.log) and verify the installed cliogate version is current.", route)
	}
	var success bool
	if err := json.Unmarshal(bytes.TrimSpace(payload), &success); err != nil {
		return fmt.Errorf("ClioGate %s returned a non-JSON response (likely an HTTP error page). Check the Creatio application logs (Error.log) and verify the installed cliogate version is current.", route)
	}
	if !success {
		return fmt.Errorf("ClioGate %s returned false. Check the Creatio application logs for details.", route)
	}
	return nil
}

// PingApplication is ApplicationPing.Ping: a GET of the site root (.NET Core) or of /0/ping. Only a failed login
// makes it false: ExecuteGetRequest answers an empty body for a request that got no answer.
func (c *Client) PingApplication(ctx context.Context) bool {
	target := c.config.BaseURL
	if !c.config.IsNetCore {
		target = c.serviceURL("ping")
	}
	requestCtx, cancel := context.WithTimeout(ctx, workspaceSyncDownloadTimeout)
	defer cancel()
	response, _, err := c.doAuthenticated(requestCtx, c.requestClient(), func() (*http.Request, error) {
		return http.NewRequestWithContext(requestCtx, http.MethodGet, target, nil)
	})
	if err != nil {
		return !isLoginError(err)
	}
	_, _ = io.Copy(io.Discard, io.LimitReader(response.Body, maxResponseBytes))
	response.Body.Close()
	return true
}

// workspaceSyncSafeName is GetSafePackageName: spaces removed, a comma closes one JSON string and opens the next.
func workspaceSyncSafeName(packageName string) string {
	return strings.ReplaceAll(strings.ReplaceAll(packageName, " ", ""), ",", `","`)
}

// DownloadPackageArchive is PackageDownloader's GetZipPackages download of one package into filePath.
func (c *Client) DownloadPackageArchive(ctx context.Context, packageName, filePath string) error {
	return c.workspaceSyncDownload(ctx, "ServiceModel/PackageInstallerService.svc/GetZipPackages",
		`["`+workspaceSyncSafeName(packageName)+`"]`, filePath)
}

// DownloadAutogeneratedFolder is Downloader's GetAutogeneratedFolder download of one package into filePath.
func (c *Client) DownloadAutogeneratedFolder(ctx context.Context, packageName, filePath string) error {
	return c.workspaceSyncDownload(ctx, "rest/CreatioApiGateway/GetAutogeneratedFolder",
		`"`+workspaceSyncSafeName(packageName)+`"`, filePath)
}

// workspaceSyncDownload is Creatio.Client.DownloadFile: the answer of a POST written to a file when the status
// is a success, otherwise WebException's protocol error.
func (c *Client) workspaceSyncDownload(ctx context.Context, route, body, filePath string) error {
	if !validServiceRoute(route) {
		return fmt.Errorf("invalid Creatio service route")
	}
	requestCtx, cancel := context.WithTimeout(ctx, workspaceSyncDownloadTimeout)
	defer cancel()
	response, _, err := c.doAuthenticated(requestCtx, c.requestClient(), func() (*http.Request, error) {
		request, err := http.NewRequestWithContext(requestCtx, http.MethodPost, c.serviceURL(route), strings.NewReader(body))
		if err != nil {
			return nil, err
		}
		request.Header.Set("Content-Type", "application/json")
		return request, nil
	})
	if err != nil {
		return workspaceSyncFault(err, false)
	}
	defer response.Body.Close()
	if response.StatusCode < 200 || response.StatusCode >= 300 {
		return fmt.Errorf("The remote server returned an error: (%d) %s.", response.StatusCode, http.StatusText(response.StatusCode))
	}
	output, err := os.Create(filePath)
	if err != nil {
		return err
	}
	written, copyErr := io.Copy(output, io.LimitReader(response.Body, workspaceSyncDownloadLimit+1))
	closeErr := output.Close()
	switch {
	case copyErr != nil:
		return workspaceSyncFault(copyErr, false)
	case written > workspaceSyncDownloadLimit:
		return fmt.Errorf("%w: %d bytes", errResponseTooLarge, workspaceSyncDownloadLimit)
	}
	return closeErr
}
